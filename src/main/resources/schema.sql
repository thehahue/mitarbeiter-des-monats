CREATE TABLE IF NOT EXISTS MITARBEITER (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR(80) NOT NULL UNIQUE,
    RANKING INTEGER NOT NULL UNIQUE
);

-- Der Status bleibt auch dann erhalten, wenn eine leere Rangliste gespeichert wird.
CREATE TABLE IF NOT EXISTS MITARBEITER_STATUS (
    ID INTEGER PRIMARY KEY CHECK (ID = 1),
    INITIALIZED BOOLEAN NOT NULL
);
INSERT INTO MITARBEITER_STATUS (ID, INITIALIZED)
SELECT 1, FALSE WHERE NOT EXISTS (SELECT 1 FROM MITARBEITER_STATUS WHERE ID = 1);
