    ('Thomas Gruber', 4),
    ('Julia Hofer', 5),
    ('Michael Bauer', 6),
    ('Sarah Leitner', 7),
    ('David Fischer', 8),
    ('Elena Mayer', 9)
) AS BEISPIELE(NAME, RANKING)
WHERE EXISTS (SELECT 1 FROM MITARBEITER_STATUS WHERE ID = 1 AND INITIALIZED = FALSE)
  AND NOT EXISTS (SELECT 1 FROM MITARBEITER);
